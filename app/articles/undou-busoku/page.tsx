const WOMAN_STEPS = 5832 // 令和元年 女性（20歳以上）の平均歩数

const nowSteps = [3000, 4000, 5000, WOMAN_STEPS, 7000]
const gapMin = (s: number) => Math.max(0, Math.round((TARGET_STEPS - s) / STEPS_PER_MIN))


const EER = 2050
const W = 53.1
const K = 0.712
const cuts = [100, 200, 300]
// 理論上、体重が落ち着くまでの減少量（kg）
const settle = (cut: number) => W * ((K * cut) / EER)
// 7,000kcal＝1kg で1年続いたと仮定した単純計算（kg）
const naive = (cut: number) => (cut * 365) / 7000
const f1 = (n: number) => n.toFixed(1)


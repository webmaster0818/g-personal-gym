const weekly = (p: { days: number; min: number }) => p.days * p.min
const note = (w: number) => {
  if (w >= BACK_DEATH) return `総死亡（約${BACK_DEATH}分/週）・心血管疾患（約${BACK_CVD}分/週）とも、リスク比が1.00に戻る時間以上`
  if (w >= BACK_CVD) return `心血管疾患でリスク比が1.00に戻る約${BACK_CVD}分/週以上`
  if (w >= LOW_DEATH && w <= LOW_CVD) return 'リスク比が最も低かった約40〜60分/週の範囲'
  return 'リスク比が最も低かった時間（約40〜60分/週）より長い'
}

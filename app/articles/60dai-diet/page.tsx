const prot = [
  { age: '50〜64歳', kcal: 1950, lo: 14, hi: 20, rda: 50 },
  { age: '65〜74歳', kcal: 1850, lo: 15, hi: 20, rda: 50 },
].map((r) => ({ ...r, gLo: Math.round((r.kcal * r.lo) / 100 / 4), gHi: Math.round((r.kcal * r.hi) / 100 / 4) }))

// 歩行（3メッツ）の消費量（安静時分を除く）＝（メッツ−1）×時間×体重。参照体重で計算

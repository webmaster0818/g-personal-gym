export type BrandFaq = { q: string; a: string }

export type OfficialStores = {
  count: number
  kind: '公式明記' | '一覧実数'
  caveat?: string
  sourceUrl: string
  asOf: string
}

export type BrandInfo = {
  slug: string
  name: string
  tagline: string
  womenOnly: boolean
  intro: string[]
  features: string[]
  pricingNote: string
  trialNote: string
  faq: BrandFaq[]
  officialUrl: string
  /** A8等の計測リンク。未設定なら公式URLへ送る（生URLでの送客は成果が計上されないため） */
  affiliateUrl?: string
  officialStores?: OfficialStores
  /** 口コミに多いテーマと注意点（GYM_REVIEWS の店舗要約から編集部が整理。stores は GYM_REVIEWS のキー）。持つブランドだけ title/h1 に「口コミ・評判」を足す */
  reviewThemes?: ReviewThemes
  /** 表示用の最終更新日（公式・口コミを確認した日）。未設定なら表示しない */
  updated?: string
  /** title の年月。未設定なら既定（2026年8月＝前回の公式確認） */
  titleMonth?: string
  /** 当サイト掲載店のうち、公式の店舗一覧に見当たらない店（店名→状況）。店舗一覧と口コミ節で注記する */
  unlistedStores?: { checked: string; stores: Record<string, string> }
}

export type ReviewTheme = {
  title: string
  text: string
  stores: string[] // 根拠にした店舗（GYM_REVIEWS のキー＝出典リンクに解決される）
}

export type ReviewThemes = {
  basis: string // 件数以外の前提（表示用。店舗数・件数はコンポーネントがデータから算出）
  good: ReviewTheme[]
  caution: ReviewTheme[]
}

